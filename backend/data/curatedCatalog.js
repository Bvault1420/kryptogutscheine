const FALLBACK_COUNTRY = 'DE';

export function getCuratedIds(country = FALLBACK_COUNTRY) {
  const code = String(country || FALLBACK_COUNTRY).toUpperCase();
  return CURATED_BY_COUNTRY[code] || CURATED_BY_COUNTRY[FALLBACK_COUNTRY];
}

export function isCuratedIdBlocked(id) {
  const lower = String(id || '').toLowerCase();
  return CURATED_BLOCK_PATTERNS.some((p) => lower.includes(p));
}

export function isCuratedProductId(id, country) {
  if (!id || isCuratedIdBlocked(id)) return false;
  return getCuratedIds(country).includes(id);
}

export function isCuratedProductIdAnyCountry(id) {
  if (!id || isCuratedIdBlocked(id)) return false;
  return Object.values(CURATED_BY_COUNTRY).some((list) => list.includes(id));
}

export function curatedCatalogSize(country) {
  return getCuratedIds(country).length;
}
