export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'de') return saved;
  } catch {
    /* ignore */
  }
  const browser = (navigator.language || 'de').toLowerCase();
  return browser.startsWith('en') ? 'en' : 'de';
}

export function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'de';
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = next;
  window.dispatchEvent(new CustomEvent('Kryptogutscheine:lang-change'));
}

export function initLang() {
  document.documentElement.lang = getLang();
}

export function t(key, vars = {}) {
  const lang = getLang();
  let str = STRINGS[lang]?.[key] ?? STRINGS.de[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  });
  return str;
}

export function getLocale() {
  return getLang() === 'en' ? 'en-GB' : 'de-DE';
}
